CREATE TABLE IF NOT EXISTS task_input_requests (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 source_task_id BIGINT UNSIGNED NOT NULL,
 data_registry_id BIGINT UNSIGNED NOT NULL UNIQUE,
 exchange_id BIGINT UNSIGNED NOT NULL UNIQUE,
 requester_id BIGINT UNSIGNED NOT NULL,
 responsible_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(240) NOT NULL,
 expected_result TEXT NOT NULL,
 due_date DATE NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'waiting',
 version INT NOT NULL DEFAULT 1,
 latest_response_id BIGINT UNSIGNED NULL,
 accepted_response_id BIGINT UNSIGNED NULL,
 request_key CHAR(64) NOT NULL UNIQUE,
 dedupe_key CHAR(64) NULL UNIQUE,
 payload_hash CHAR(64) NOT NULL,
 cancel_reason TEXT NULL,
 cancelled_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (project_id) REFERENCES projects(id),
 FOREIGN KEY (source_task_id) REFERENCES tasks(id),
 FOREIGN KEY (data_registry_id) REFERENCES project_data_registry(id),
 FOREIGN KEY (exchange_id) REFERENCES project_task_exchange(id),
 FOREIGN KEY (requester_id) REFERENCES users(id),
 FOREIGN KEY (responsible_id) REFERENCES users(id),
 INDEX idx_input_request_task (source_task_id, id),
 INDEX idx_input_request_inbox (responsible_id, state, due_date),
 INDEX idx_input_request_review (requester_id, state, due_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS task_input_responses (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 request_id BIGINT UNSIGNED NOT NULL,
 responded_by BIGINT UNSIGNED NOT NULL,
 response_text TEXT NOT NULL,
 source_reference VARCHAR(2000) NOT NULL,
 source_revision VARCHAR(160) NOT NULL,
 decision VARCHAR(20) NOT NULL DEFAULT 'pending',
 decision_comment TEXT NULL,
 decided_by BIGINT UNSIGNED NULL,
 decided_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (request_id) REFERENCES task_input_requests(id),
 FOREIGN KEY (responded_by) REFERENCES users(id),
 FOREIGN KEY (decided_by) REFERENCES users(id),
 INDEX idx_input_response_request (request_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
